CREATE UNIQUE INDEX IF NOT EXISTS ux_produto_id_empresa ON produto (id, empresa_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pedido_id_obra ON pedido (id, obra_id);

CREATE TABLE IF NOT EXISTS movimentacao_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id INTEGER NOT NULL,
    obra_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    pedido_id INTEGER NOT NULL,
    registrado_por_usuario_id INTEGER NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    quantidade NUMERIC(12, 2) NOT NULL,
    saldo_anterior NUMERIC(12, 2) NOT NULL,
    saldo_posterior NUMERIC(12, 2) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    protocolo_pedido VARCHAR(50) NOT NULL,
    produto_nome VARCHAR(150) NOT NULL,
    unidade VARCHAR(30) NOT NULL,
    CONSTRAINT ck_movimentacao_tipo CHECK (tipo = 'saida_pedido'),
    CONSTRAINT ck_movimentacao_quantidade
        CHECK (quantidade > 0 AND quantidade <= 9999999999.99),
    CONSTRAINT ck_movimentacao_saldo_anterior
        CHECK (saldo_anterior BETWEEN 0 AND 9999999999.99),
    CONSTRAINT ck_movimentacao_saldo_posterior
        CHECK (saldo_posterior BETWEEN 0 AND 9999999999.99),
    CONSTRAINT ck_movimentacao_saldos
        CHECK (saldo_anterior - quantidade = saldo_posterior),
    CONSTRAINT ux_movimentacao_pedido_produto_tipo
        UNIQUE (empresa_id, pedido_id, produto_id, tipo),
    CONSTRAINT fk_movimentacao_obra_empresa
        FOREIGN KEY (obra_id, empresa_id)
        REFERENCES obra (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimentacao_produto_empresa
        FOREIGN KEY (produto_id, empresa_id)
        REFERENCES produto (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimentacao_usuario_empresa
        FOREIGN KEY (registrado_por_usuario_id, empresa_id)
        REFERENCES usuario (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimentacao_pedido_obra
        FOREIGN KEY (pedido_id, obra_id)
        REFERENCES pedido (id, obra_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_movimentacao_obra_periodo
    ON movimentacao_estoque (empresa_id, obra_id, ocorrido_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_movimentacao_produto_periodo
    ON movimentacao_estoque (empresa_id, produto_id, ocorrido_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_movimentacao_empresa_periodo
    ON movimentacao_estoque (empresa_id, ocorrido_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_movimentacao_aprovador_periodo
    ON movimentacao_estoque
        (empresa_id, registrado_por_usuario_id, ocorrido_em DESC, id DESC);
